"""Longitudinal ping-pong reader for one route (StarPilot accord-PTM, Honda Bosch openpilot long).

usage:  python long_pingpong_read.py <route>      e.g.  0000009d--371ec93849
        add --rebuild to re-extract the cache.

Decodes with the FORK's cereal at 311c4cc0 (regenerated by `git show` into _scratch/cache/cereal_311c4cc0 when
missing) -- the kit's own cereal has the slot-137 collision and lacks starpilotPlan.  Each segment is extracted once,
in parallel, to _scratch/cache/<route>/long_seg<N>.npz; everything after that is vectorised numpy.

Reports, for openpilot-long-engaged lead-following time:
  * experimentalMode duty + flips/min (selfdriveState = the mode the planner uses; starpilotPlan's copy beside it)
  * the MPC a-change weight starpilotPlan.accelerationJerk: its distinct values and flips/min (the aEgo-sign switch)
  * gap: dRel vs the planner's desiredFollowDistance and vs 1.25 s x v; band-passed (2-8 s period) gap oscillation
    amplitude and dominant period; PING-PONG fraction = band envelope > 1 m, split chill vs blended
  * aEgo sign-crossing rate (raw and with a +-0.05 m/s^2 hysteresis)
  * actuators.accel -> aEgo lag (cross-correlation peak, 0..2 s)
  * implied Honda Bosch gas gain from ACC_CONTROL (0x1DF) GAS_COMMAND -- BELIEF: assumes wind factor 1.0; the
    carcontroller's learned HondaGasFactorParams is not logged at 311c4cc0.
"""
