def i16be(d, i):
    v = (d[i] << 8) | d[i + 1]
    return v - 0x10000 if v & 0x8000 else v


# ============================================================================ extraction =========
def extract_segment(path):
    """One rlog.zst -> per-BATCH arrays PLUS per-frame NATIVE sequences.

    The batch grid is convenient (all channels aligned, one row per ~10 ms) and is what the
    time-domain tests use.  But the panda's ~100 Hz read and the EPS's ~100 Hz transmit BEAT, so a
    few percent of batches carry two copies of a frame and the next carries none -- up to 13% of
    `bar` on some segments.  Forward-filling that is a time-varying sample-and-hold and it is NOT
    the same pattern on the command channel, so it would bias a 27 Hz phase measurement.
    The NATIVE sequences (`n18_*`, `n14_*`, `ne4_*`) keep every frame in arrival order, which IS
    the transmitter's own uniform lattice; `native_block` below turns them into exact-phase spectra
    with no interpolation anywhere.
    """
    from rlog_parse import read_messages

    bt, bar, mot, b18_4, ang, rate_c, wang, p14, cmd, creq, cam = ([] for _ in range(11))
    n18_t, n18_bar, n18_mot, n18_b4 = [], [], [], []
    n14_t, n14_ang, n14_rate, n14_p14 = [], [], [], []
    ne4_t, ne4_cmd, ne4_req = [], [], []
    sc_t, sc_v, sc_r = [], [], []
    cc_t, cc_lat, cc_en, cc_rq = [], [], [], []
    cs_t, cs_v, cs_pr, cs_ang = [], [], [], []

    for evt in read_messages(path):
        try:
            w = evt.which()
        except Exception:
            continue
        tm = evt.logMonoTime * 1e-9
        if w == "can":
            g = dict(bar=np.nan, mot=np.nan, b4=np.nan, ang=np.nan, rate=np.nan, wang=np.nan,
                     p14=np.nan, cmd=np.nan, creq=np.nan, cam=np.nan)
            for m in evt.can:
                src, addr = int(m.src), int(m.address)
                d = bytes(m.dat)
                if src == 1 and addr == 0x18F and len(d) >= 5:
                    g["bar"] = i16be(d, 0) * -1.0
                    g["mot"] = float(i16be(d, 2))
                    g["b4"] = float(d[4])
                    n18_t.append(tm); n18_bar.append(g["bar"])
                    n18_mot.append(g["mot"]); n18_b4.append(g["b4"])
                elif src == 1 and addr == 0x14A and len(d) >= 7:
                    g["ang"] = i16be(d, 0) * -0.1
                    g["rate"] = i16be(d, 2) * -1.0
                    g["wang"] = i16be(d, 5) * -0.1
                    g["p14"] = float(d[4])
                    n14_t.append(tm); n14_ang.append(g["ang"])
                    n14_rate.append(g["rate"]); n14_p14.append(g["p14"])
                elif src == 129 and addr == 0x0E4 and len(d) >= 3:
                    g["cmd"] = float(i16be(d, 0))
                    g["creq"] = float((d[2] >> 7) & 1)
                    ne4_t.append(tm); ne4_cmd.append(g["cmd"]); ne4_req.append(g["creq"])
                elif src == 2 and addr == 0x0E4 and len(d) >= 3:
                    g["cam"] = float(i16be(d, 0))
            if np.isnan(g["ang"]) and np.isnan(g["bar"]) and np.isnan(g["cmd"]):
                continue
            bt.append(tm)
            bar.append(g["bar"]); mot.append(g["mot"]); b18_4.append(g["b4"])
            ang.append(g["ang"]); rate_c.append(g["rate"]); wang.append(g["wang"])
            p14.append(g["p14"]); cmd.append(g["cmd"]); creq.append(g["creq"]); cam.append(g["cam"])
        elif w == "sendcan":
            for m in evt.sendcan:
                if int(m.src) == 1 and int(m.address) == 0x0E4:
                    d = bytes(m.dat)
                    if len(d) >= 3:
                        sc_t.append(tm); sc_v.append(float(i16be(d, 0)))
                        sc_r.append(float((d[2] >> 7) & 1))
        elif w == "carControl":
            c = evt.carControl
            cc_t.append(tm); cc_lat.append(float(bool(c.latActive)))
            cc_en.append(float(bool(c.enabled)))
            try:
                cc_rq.append(float(c.actuators.torque))
            except Exception:
                cc_rq.append(np.nan)
        elif w == "carState":
            c = evt.carState
            cs_t.append(tm); cs_v.append(float(c.vEgo))
            cs_pr.append(float(bool(c.steeringPressed)))
            cs_ang.append(float(c.steeringAngleDeg))

    d = dict(t=np.array(bt), bar=np.array(bar), mot=np.array(mot), b18_4=np.array(b18_4),
             ang=np.array(ang), rate_c=np.array(rate_c), wang=np.array(wang),
             p14=np.array(p14), cmd=np.array(cmd), creq=np.array(creq), cam=np.array(cam),
             sc_t=np.array(sc_t), sc_v=np.array(sc_v), sc_r=np.array(sc_r),
             n18_t=np.array(n18_t), n18_bar=np.array(n18_bar), n18_mot=np.array(n18_mot),
             n18_b4=np.array(n18_b4),
             n14_t=np.array(n14_t), n14_ang=np.array(n14_ang), n14_rate=np.array(n14_rate),
             n14_p14=np.array(n14_p14),
             ne4_t=np.array(ne4_t), ne4_cmd=np.array(ne4_cmd), ne4_req=np.array(ne4_req))
    # slow services: zero-order hold onto the batch lattice (they are all <= 20 Hz content)
    for nm, tt, vv in (("cc_lat", cc_t, cc_lat), ("cc_en", cc_t, cc_en), ("cc_rq", cc_t, cc_rq),
                       ("cs_v", cs_t, cs_v), ("cs_pr", cs_t, cs_pr), ("cs_ang", cs_t, cs_ang)):
        tt, vv = np.asarray(tt, float), np.asarray(vv, float)
        d[nm] = (np.interp(d["t"], tt, vv) if len(tt) > 1
                 else np.full(len(d["t"]), np.nan))
    return d


def hold_fill(x):
    """Forward-fill NaNs (a batch that happened to carry no copy of that frame), then back-fill the
    leading run.  Returns (filled, n_filled)."""
    x = np.asarray(x, float).copy()
    bad = ~np.isfinite(x)
    if bad.all():
        return x, int(bad.sum())
    idx = np.where(~bad, np.arange(len(x)), 0)
    np.maximum.accumulate(idx, out=idx)
    x = x[idx]
    first = np.flatnonzero(~bad)[0]
    x[:first] = x[first]
    return x, int(bad.sum())


def fs_lattice(t):
    """(n-1)/span over the longest gap-free stretch.  🛑 NEVER 1/median(dt)."""
    t = np.asarray(t, float)
    if len(t) < 3:
        return 100.0
    dt = np.diff(t)
    brk = np.flatnonzero(dt > 0.05)
    edges = [0] + list(brk + 1) + [len(t)]
    a, b = max(zip(edges[:-1], edges[1:]), key=lambda ab: ab[1] - ab[0])
    if b - a < 3 or t[b - 1] <= t[a]:
        return float(1.0 / np.median(dt))
    return float((b - a - 1) / (t[b - 1] - t[a]))


def build_route(route, verbose=True):
    stem, nseg = ROUTES[route]
    out = []
    for s in range(nseg):
        p = RLOGDIR / f"{stem}--{s}--rlog.zst"
        if not p.exists():
            continue
        d = extract_segment(p)
        if len(d["t"]) < 100:
            continue
        nf = {}
        for k in ("bar", "mot", "b18_4", "ang", "rate_c", "wang", "p14", "cmd", "creq", "cam"):
            d[k], nf[k] = hold_fill(d[k])
        d["_fs"] = fs_lattice(d["t"])
        d["_seg"] = s
        d["_route"] = route
        d["_nfill"] = nf
        if verbose:
            eng = np.mean(d["cc_lat"] > 0.5) * 100
            print(f"  {route} seg{s:2d}: n={len(d['t']):5d}  fs={d['_fs']:.4f}  "
                  f"eng={eng:5.1f}%  v={np.nanmean(d['cs_v']):5.2f}  "
                  f"fill(bar/cmd)={nf['bar']}/{nf['cmd']}", flush=True)
        out.append(d)
    return out


def save_route(route, segs):
    CACHE.mkdir(parents=True, exist_ok=True)
    tag = route.split("/")[1]
    for d in segs:
        np.savez_compressed(CACHE / f"loopop_{tag}_s{d['_seg']}.npz",
                            **{k: v for k, v in d.items() if isinstance(v, np.ndarray)},
                            _fs=np.array([d["_fs"]]), _seg=np.array([d["_seg"]]),
                            _route=np.array([route]))


def load_route(route):
    tag = route.split("/")[1]
    out = []
    for p in sorted(CACHE.glob(f"loopop_{tag}_s*.npz"),
                    key=lambda q: int(q.stem.split("_s")[-1])):
        z = np.load(p, allow_pickle=False)
        d = {k: z[k] for k in z.files}
        d["_fs"] = float(d["_fs"][0])
        d["_seg"] = int(d["_seg"][0])
        d["_route"] = route
        out.append(d)
    return out


