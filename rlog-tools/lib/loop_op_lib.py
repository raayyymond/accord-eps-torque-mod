def mask_engaged(d):
    return (d["cc_lat"] > 0.5) & (d["creq"] > 0.5)


def mask_manual(d):
    return (d["cc_lat"] < 0.5) & (np.abs(d["cs_v"]) > 1.0)


def lattice_ok(d):
    t = np.asarray(d["t"], float)
    ok = np.ones(len(t), bool)
    ok[1:] = np.diff(t) < LATTICE_GAP
    return ok


def episodes(d, mask, nperseg=NPERSEG, ep_max=EP_MAX):
    """Maximal lattice-contiguous runs of `mask`, split at `ep_max`, truncated to whole blocks."""
    m = np.asarray(mask, bool) & lattice_ok(d)
    idx = np.flatnonzero(m)
    if not len(idx):
        return
    starts, ends = [idx[0]], []
    for a, b in zip(idx[:-1], idx[1:]):
        if b != a + 1:
            ends.append(a + 1)
            starts.append(b)
    ends.append(idx[-1] + 1)
    for s, e in zip(starts, ends):
        while e - s >= nperseg:
            n = min(ep_max, e - s)
            n -= n % nperseg
            yield (s, s + n)
            s += n


# ====================================================== NATIVE-LATTICE (exact-phase) spectra =====
# 🛑 THIS IS THE PATH EVERY PHASE / GROUP-DELAY CLAIM IS BUILT ON.  No interpolation anywhere.
#
# Each transmitter (the EPS for 0x18F and 0x14A, openpilot for 0x0E4) emits on its OWN uniform
# ~100 Hz lattice.  The panda's batch timestamp quantises arrival to +/-5 ms, but a straight-line
# fit of batch-time vs frame-index over thousands of frames averages that jitter down to well under
# 0.1 ms, recovering the transmitter's lattice:      t_c(k) = a_c + b_c * k
# A block of N frames starting at index k0 is then a UNIFORM sample record whose absolute start
# time is known.  Its DFT is referred to a common epoch by  X_j *= exp(-j*2*pi*f_j*(t_c(k0)-T_ref)),
# which is an EXACT phase correction -- unlike `np.interp` onto a foreign grid, whose group delay
# is a fraction of a frame that drifts with the comma/car clock beat (0-10 ms = 0-97 deg at 27 Hz).
NATIVE = {"bar": ("n18_t", "n18_bar"), "mot": ("n18_t", "n18_mot"), "b18_4": ("n18_t", "n18_b4"),
          "ang": ("n14_t", "n14_ang"), "rate_c": ("n14_t", "n14_rate"),
          "p14": ("n14_t", "n14_p14"),
          "cmd": ("ne4_t", "ne4_cmd"), "creq": ("ne4_t", "ne4_req"),
          "sc_cmd": ("sc_t", "sc_v")}


def lattice_fit(t):
    """(a, b, rms_resid_ms, n) for t[k] ~ a + b*k, ordinary LS over the whole run."""
    t = np.asarray(t, float)
    n = len(t)
    k = np.arange(n, dtype=float)
    b, a = np.polyfit(k, t, 1)
    resid = t - (a + b * k)
    return float(a), float(b), float(np.std(resid) * 1e3), n


def native_meta(d):
    """Per-channel lattice fit + the fs mismatch that limits the phase accuracy."""
    out = {}
    for ch, (tk, vk) in NATIVE.items():
        if tk not in d or len(d[tk]) < 100:
            continue
        a, b, rms, n = lattice_fit(d[tk])
        out[ch] = dict(a=a, b=b, fs=1.0 / b, jit_ms=rms, n=n)
    return out


def native_block(d, ch, t_start, nperseg, meta=None):
    """(X, f, t_actual) for one Hann-windowed, detrended block of channel `ch` beginning at the
    first native sample at or after `t_start`.  Returns None if the block runs off the end or
    crosses a lattice gap > 15 ms.

    🛑 The lattice fit is LOCAL TO THE BLOCK, not global to the segment.  A whole-segment fit is
    destroyed by any pause in the log -- measured: it drags the apparent 0x18F rate to 99.56 Hz and
    the fit residual to 23 ms on route 6d, which would be a 196 deg epoch error at 27 Hz.  A block
    that survives the >15 ms gap test is on a clean lattice by construction, so its own 512-point
    LS fit is exact: with ~1 ms per-sample timestamp jitter the intercept sd is 1/sqrt(512) =
    0.04 ms and the block-end slope error is ~0.15 ms.  Both are negligible at 27 Hz.
    """
    tk, vk = NATIVE[ch]
    t, v = np.asarray(d[tk], float), np.asarray(d[vk], float)
    if len(t) < nperseg + 2:
        return None
    k0 = int(np.searchsorted(t, t_start, side="left"))
    if k0 + nperseg > len(t):
        return None
    seg_t = t[k0:k0 + nperseg]
    if np.max(np.diff(seg_t)) > LATTICE_GAP:
        return None
    x = v[k0:k0 + nperseg]
    if not np.all(np.isfinite(x)):
        return None
    r = np.arange(nperseg, dtype=float)
    b, a = np.polyfit(r, seg_t, 1)          # local lattice: t[k0+i] ~ a + b*i
    x = x - np.polyval(np.polyfit(r, x, 1), r)
    X = np.fft.rfft(x * np.hanning(nperseg))
    f = np.fft.rfftfreq(nperseg, b)
    return X, f, a


def native_spectra(d, t0, t1, xch, ykey_ch, nperseg=NPERSEG, hop_s=None):
    """Averaged auto/cross spectra of (xch, ych) over [t0, t1] wall-clock, exact relative phase.

    Blocks are laid out on WALL CLOCK (both channels get the same requested start time), then each
    channel's exact block-start time is used to refer its DFT to that requested epoch.
    Sxy = conj(X)*Y  =>  H1 = Sxy/Sxx and arg(Sxy) = arg(Y) - arg(X).
    """
    meta = None
    for ch in (xch, ykey_ch):
        tk, _ = NATIVE[ch]
        if tk not in d or len(d[tk]) < nperseg + 2:
            return None
    dur = nperseg / 100.0
    hop = dur / 2 if hop_s is None else hop_s
    f_ref = None
    Sxx = Syy = Sxy = None
    n = 0
    ts = t0
    while ts + dur <= t1:
        bx = native_block(d, xch, ts, nperseg, meta)
        by = native_block(d, ykey_ch, ts, nperseg, meta)
        ts += hop
        if bx is None or by is None:
            continue
        X, fx, tx = bx
        Y, fy, ty = by
        if f_ref is None:
            f_ref = 0.5 * (fx + fy)
            Sxx = np.zeros(len(f_ref)); Syy = np.zeros(len(f_ref))
            Sxy = np.zeros(len(f_ref), complex)
        # refer both to the requested epoch `ts - hop`
        X = X * np.exp(-1j * 2 * np.pi * fx * (tx - (ts - hop)))
        Y = Y * np.exp(-1j * 2 * np.pi * fy * (ty - (ts - hop)))
        Sxx += np.abs(X) ** 2
        Syy += np.abs(Y) ** 2
        Sxy += np.conj(X) * Y
        n += 1
    if not n:
        return None
    return f_ref, Sxx / n, Syy / n, Sxy / n, n


def native_episodes(d, mask, nperseg=NPERSEG, ep_max=EP_MAX):
    """Episode (t0, t1) wall-clock windows from a mask defined on the BATCH grid."""
    for i0, i1 in episodes(d, mask, nperseg, ep_max):
        yield float(d["t"][i0]), float(d["t"][i1 - 1])


def collect_native(route, mask_fn, xch="cmd", ych="bar", nperseg=NPERSEG, ep_max=EP_MAX,
                   extra=None, segs=None):
    out = []
    for d in (segs if segs is not None else load_route(route)):
        m = mask_fn(d)
        for t0, t1 in native_episodes(d, m, nperseg, ep_max):
            r = native_spectra(d, t0, t1, xch, ych, nperseg)
            if r is None or r[4] < 2:
                continue
            f, Sxx, Syy, Sxy, nb = r
            i0 = int(np.searchsorted(d["t"], t0)); i1 = int(np.searchsorted(d["t"], t1))
            v = np.abs(np.asarray(d["cs_v"], float)[i0:i1 + 1])
            rec = dict(f=f, Sxx=Sxx, Syy=Syy, Sxy=Sxy, nblk=nb, route=route, seg=int(d["_seg"]),
                       i0=i0, i1=i1, t0=t0, t1=t1, sec=t1 - t0, fs=d["_fs"],
                       v_mean=float(v.mean()), v_p5=float(np.percentile(v, 5)),
                       v_p95=float(np.percentile(v, 95)))
            if extra is not None:
                rec.update(extra(d, i0, i1))
            out.append(rec)
    return out


# ============================================================================ spectra ============
def ep_spectra(d, i0, i1, xkey, ykey, nperseg=NPERSEG, hop=None, tau=0.0, xscale=1.0, yscale=1.0):
    """Within-episode averaged auto/cross spectra of (x, y).  Sxy = conj(X)*Y  =>  H1 = Sxy/Sxx.

    `tau` rotates Y by exp(+j*w*tau) -- i.e. it treats Y as `tau` seconds STALE.  Zero here by
    construction (batch indexing); exposed so a claim can be re-run under the legacy +9.9 ms.
    """
    hop = nperseg // 2 if hop is None else hop
    fs = d["_fs"]
    xa = np.asarray(d[xkey], float) * xscale
    ya = np.asarray(d[ykey], float) * yscale
    w = np.hanning(nperseg)
    f = np.fft.rfftfreq(nperseg, 1 / fs)
    rot = np.exp(1j * 2 * np.pi * f * tau)
    r = np.arange(nperseg, dtype=float)
    Sxx = np.zeros(len(f)); Syy = np.zeros(len(f)); Sxy = np.zeros(len(f), complex)
    n = 0
    for i in range(i0, i1 - nperseg + 1, hop):
        x, y = xa[i:i + nperseg], ya[i:i + nperseg]
        if not (np.all(np.isfinite(x)) and np.all(np.isfinite(y))):
            continue
        x = x - np.polyval(np.polyfit(r, x, 1), r)
        y = y - np.polyval(np.polyfit(r, y, 1), r)
        X = np.fft.rfft(x * w)
        Y = np.fft.rfft(y * w) * rot
        Sxx += np.abs(X) ** 2
        Syy += np.abs(Y) ** 2
        Sxy += np.conj(X) * Y
        n += 1
    if not n:
        return f, None, None, None, 0
    return f, Sxx / n, Syy / n, Sxy / n, n


def collect(route, mask_fn, xkey="cmd", ykey="bar", nperseg=NPERSEG, tau=0.0,
            ep_max=EP_MAX, extra=None, segs=None):
    out = []
    for d in (segs if segs is not None else load_route(route)):
        for i0, i1 in episodes(d, mask_fn(d), nperseg, ep_max):
            f, Sxx, Syy, Sxy, nb = ep_spectra(d, i0, i1, xkey, ykey, nperseg, tau=tau)
            if nb < 2:
                continue
            v = np.abs(np.asarray(d["cs_v"], float)[i0:i1])
            rec = dict(f=f, Sxx=Sxx, Syy=Syy, Sxy=Sxy, nblk=nb, route=route, seg=int(d["_seg"]),
                       i0=int(i0), i1=int(i1), sec=(i1 - i0) / d["_fs"], fs=d["_fs"],
                       v_mean=float(v.mean()), v_p5=float(np.percentile(v, 5)),
                       v_p95=float(np.percentile(v, 95)))
            if extra is not None:
                rec.update(extra(d, i0, i1))
            out.append(rec)
    return out


def stack(recs):
    if not recs:
        return None, None, None, None, 0
    f = recs[0]["f"]
    wgt = np.array([r["nblk"] for r in recs], float)
    Sxx = np.tensordot(wgt, np.array([r["Sxx"] for r in recs]), 1) / wgt.sum()
    Syy = np.tensordot(wgt, np.array([r["Syy"] for r in recs]), 1) / wgt.sum()
    Sxy = np.tensordot(wgt, np.array([r["Sxy"] for r in recs]), 1) / wgt.sum()
    return f, Sxx, Syy, Sxy, len(recs)


def coh(Sxx, Syy, Sxy):
    with np.errstate(divide="ignore", invalid="ignore"):
        return np.abs(Sxy) ** 2 / (Sxx * Syy)


def g2_crit(K, alpha=0.05):
    """Significance floor for magnitude-squared coherence with K independent averages."""
    return 1.0 - alpha ** (1.0 / max(K - 1, 1))


def bp_sd(g2, K):
    """Bendat-Piersol relative sd of |H| (and, in rad, the sd of arg H)."""
    g2 = np.clip(g2, 1e-9, 1 - 1e-9)
    return np.sqrt((1 - g2) / (2 * K * g2))


# ============================================================================ group delay ========
def band_delay(f, Sxy, lo, hi, wgt=None):
    """Group delay over [lo,hi] from a WEIGHTED least-squares fit of unwrapped arg(Sxy) vs f.

    Returns (tau_s, phi0_deg, r2, n).  tau > 0 means Y LAGS X (X leads => X could be driving Y).
    Sign convention: Sxy = conj(X)*Y, so arg(Sxy) = arg(Y) - arg(X);  a pure delay
    y(t) = x(t - tau) gives arg = -w*tau  =>  slope d(arg)/df = -2*pi*tau.
    """
    sel = (f >= lo) & (f <= hi)
    ff = f[sel]
    if sel.sum() < 3:
        return np.nan, np.nan, np.nan, int(sel.sum())
    ph = np.unwrap(np.angle(Sxy[sel]))
    w = np.ones(sel.sum()) if wgt is None else np.nan_to_num(wgt[sel], nan=0.0, posinf=0.0)
    if w.sum() <= 0:
        return np.nan, np.nan, np.nan, int(sel.sum())
    W = w / w.sum()
    fm, pm = np.sum(W * ff), np.sum(W * ph)
    cov = np.sum(W * (ff - fm) * (ph - pm))
    var = np.sum(W * (ff - fm) ** 2)
    if var <= 0:
        return np.nan, np.nan, np.nan, int(sel.sum())
    slope = cov / var
    pred = pm + slope * (ff - fm)
    ss = np.sum(W * (ph - pred) ** 2)
    st = np.sum(W * (ph - pm) ** 2)
    return (float(-slope / (2 * np.pi)), float(np.degrees(pm - slope * fm)),
            float(1 - ss / st) if st > 0 else np.nan, int(sel.sum()))


def band_stats(f, Sxx, Syy, Sxy, lo, hi, K):
    """Band-aggregated coherence, |H|, phase, delay.  Bins are SUMMED before the ratio -- the
    Bendat-Piersol band-averaged estimator, not a mean of per-bin ratios."""
    sel = (f >= lo) & (f <= hi)
    sxx, syy = float(Sxx[sel].sum()), float(Syy[sel].sum())
    sxy = complex(Sxy[sel].sum())
    if sxx <= 0 or syy <= 0:
        return dict(lo=lo, hi=hi, g2=np.nan, H=np.nan, ph=np.nan, tau_ms=np.nan, r2=np.nan,
                    rms_x=np.nan, rms_y=np.nan, ratio=np.nan, nbin=int(sel.sum()), K=K)
    g2 = abs(sxy) ** 2 / (sxx * syy)
    H = abs(sxy) / sxx
    w = coh(Sxx, Syy, Sxy) * Sxx
    tau, ph0, r2, _ = band_delay(f, Sxy, lo, hi, wgt=w)
    return dict(lo=lo, hi=hi, g2=float(g2), H=float(H), ph=float(np.degrees(np.angle(sxy))),
                tau_ms=float(tau * 1e3), r2=r2, rms_x=float(np.sqrt(sxx)),
                rms_y=float(np.sqrt(syy)), ratio=float(np.sqrt(syy / sxx)),
                nbin=int(sel.sum()), K=K, g2crit=g2_crit(K), sd_H=float(bp_sd(g2, K)))


def boot_band(recs, lo, hi, nboot=2000, seed=8585):
    """Episode bootstrap of `band_stats`.  Resamples EPISODES with replacement -- never windows."""
    rng = np.random.default_rng(seed)
    f, Sxx, Syy, Sxy, K = stack(recs)
    if K == 0:
        return None, {}
    pt = band_stats(f, Sxx, Syy, Sxy, lo, hi, K)
    if K < 4:
        return pt, {k: (np.nan, np.nan) for k in ("g2", "H", "tau_ms", "ratio")}
    keys = ("g2", "H", "tau_ms", "ratio", "ph")
    smp = {k: [] for k in keys}
    n = len(recs)
    for _ in range(nboot):
        j = rng.integers(0, n, n)
        f2, sx, sy, sc, _ = stack([recs[i] for i in j])
        r = band_stats(f2, sx, sy, sc, lo, hi, K)
        for k in keys:
            smp[k].append(r[k])
    ci = {k: (float(np.nanpercentile(smp[k], 2.5)), float(np.nanpercentile(smp[k], 97.5)))
          for k in keys}
    return pt, ci


# ============================================================================ nulls ==============
def mismatch_null(recs, shift=1, seed=4242):
    """Coherence floor from PHASE-RANDOMISED episode pairing.  Exactly 1/K in expectation."""
    K = len(recs)
    if K < 3:
        return None, 0
    rng = np.random.default_rng(seed)
    f = recs[0]["f"]
    Sxx = np.mean([r["Sxx"] for r in recs], axis=0)
    Syy = np.mean([r["Syy"] for r in recs], axis=0)
    acc = np.zeros(len(f), complex)
    for i, r in enumerate(recs):
        o = recs[(i + shift) % K]
        ph = rng.uniform(0, 2 * np.pi, len(f))
        acc += np.sqrt(r["Sxx"] * o["Syy"]) * np.exp(1j * ph)
    return coh(Sxx, Syy, acc / K), K


def fill_mask(d, ch="bar"):
    """True where the BATCH GRID value of `ch` is a forward-fill (no frame arrived in that batch).

    The panda's ~100 Hz read and the transmitter's ~100 Hz cadence beat, so a few percent of
    batches carry two copies of a frame and the next carries none -- up to 13% of `bar` on some
    segments.  Native-lattice spectra are immune; TIME-DOMAIN tests (Granger, envelopes, edges)
    are not, because a repeated sample is an artificial one-lag autocorrelation.  Detect it
    exactly: a batch is a fill iff its timestamp appears in no native frame timestamp.
    """
    tk = {"bar": "n18_t", "mot": "n18_t", "ang": "n14_t", "rate_c": "n14_t",
          "cmd": "ne4_t", "creq": "ne4_t"}[ch]
    return ~np.isin(np.asarray(d["t"], float), np.asarray(d[tk], float))


def fmt_ci(pt, ci, sf=3):
    lo, hi = ci
    return f"{pt:.{sf}g} [{lo:.{sf}g}, {hi:.{sf}g}]"
