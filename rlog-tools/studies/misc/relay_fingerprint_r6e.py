def windows(route, cache, pfx, segs, engaged=True):
    """Yield dicts with the raw window plus every covariate the tests need."""
    b_lf = butter(2, [0.5, 4.0], btype="band", fs=101.0)
    b_bp = butter(2, [F_LO, F_HI], btype="band", fs=101.0)
    out = []
    for s in segs:
        p = ROOT / cache / f"{pfx}{s}.npz"
        if not p.exists():
            continue
        d = C31.load(s, ROOT / cache, pfx)
        fs = C31.fs_of(d)
        t = np.asarray(d["t"], float)
        tq = np.asarray(d["tq"], float)
        v = np.asarray(d["cs_v"], float)
        lat = np.asarray(d["cc_lat"], float) > 0.5
        rate = np.abs(np.asarray(d["rate_c"], float))
        eff = np.abs(np.asarray(d["cs_tq"], float))
        pr = np.asarray(d["probe"], float).astype(int) if "probe" in d else None
        mask = lat if engaged else ~lat
        for a, b in C31.runs_of(mask, t, NW):
            x_lf = filtfilt(*b_lf, tq[a:b])
            x_bp = filtfilt(*b_bp, tq[a:b])
            env = np.abs(hilbert(x_bp))
            for j0 in range(0, (b - a) - NW + 1, HOPW):
                sl = slice(j0, j0 + NW)
                seg = tq[a:b][sl]
                if not np.all(np.isfinite(seg)):
                    continue
                r = dict(build=route, seg=int(s), t0=float(t[a:b][sl][0]),
                         blk=f"{s}:{a}:{j0 // (HOPW * 2)}", ep=f"{s}:{a}",
                         v=float(np.median(v[a:b][sl])), rate=float(np.median(rate[a:b][sl])),
                         eff=float(np.median(eff[a:b][sl])), fs=float(fs),
                         x=seg, x_lf=x_lf[sl], env=env[sl])
                if pr is not None:
                    q = pr[a:b][sl]
                    for nm, bit in (("b7", 0x80), ("b6", 0x40), ("b5", 0x20), ("b4", 0x10)):
                        r[nm] = float(np.mean((q & bit) != 0))
                out.append(r)
    return out


def spectra(recs):
    """Attach the periodogram, the prominence spectrum and the free 5-12 Hz argmax."""
    for r in recs:
        P = C31.periodogram(r["x"], r["fs"], nfft=NW, detrend=True)
        f = np.fft.rfftfreq(NW, 1.0 / r["fs"])
        R = G.prom_spectrum(f, P, halfwin=3.0, exclude=0.6)
        r["f"], r["P"], r["R"] = f, P, R
        m = (f >= 5.0) & (f <= 12.0) & np.isfinite(R)
        r["f_free"] = float(f[np.argmax(np.where(m, R, -np.inf))]) if m.any() else np.nan
        r["p_free"] = float(np.nanmax(np.where(m, R, np.nan))) if m.any() else np.nan
        mb = (f >= F_LO) & (f <= F_HI) & np.isfinite(R)
        r["f0"] = float(f[np.argmax(np.where(mb, R, -np.inf))]) if mb.any() else np.nan
        r["p0"] = float(np.nanmax(np.where(mb, R, np.nan))) if mb.any() else np.nan
    return recs


def prom_at(r, f_target, half=0.35):
    """Max prominence within +-half Hz of f_target; NaN above 45 Hz or off-grid."""
    if not np.isfinite(f_target) or f_target > 45.0 or f_target < 1.0:
        return np.nan
    m = (np.abs(r["f"] - f_target) <= half) & np.isfinite(r["R"])
    return float(np.nanmax(r["R"][m])) if m.any() else np.nan


