def t5(W):
    hdr("T5  IS THE 6-9 Hz CONTENT CONDITIONAL ON `|gp-0x6ae2|`?  V85 only -- the rungs exist on\n"
        "    no other build.  ⚠ `gp-0x6ae2` is the term `0xC40BC` linearised, NOT `gp-0x6b70`.")
    recs = [r for rt, arm, rr in W if rt == "V85/r6e" and arm == "engaged" for r in rr]
    if not recs:
        print("  no V85 engaged windows"); return
    b_bp = butter(2, [F_LO, F_HI], btype="band", fs=101.0)
    for r in recs:
        r["e69"] = float(np.percentile(np.abs(hilbert(filtfilt(*b_bp, r["x"]))), 99))
    print(f"{'rung':6s} {'split':>26s} {'n lo':>5s} {'n hi':>5s} | {'e_6-9 LOW':>22s} | "
          f"{'e_6-9 HIGH':>22s} | {'HIGH/LOW':>8s}")
    OUT["t5"] = {}
    for rung, name in (("b4", "|gp-0x6ae2| >= 2"), ("b5", "|gp-0x6ae2| >= 8"),
                       ("b7", "|gp-0x6abc| >= 64"), ("b6", "|gp-0x6abc| >= 512")):
        duty = np.array([r[rung] for r in recs])
        thr = float(np.median(duty))
        lo_ = [r for r in recs if r[rung] <= thr]
        hi_ = [r for r in recs if r[rung] > thr]
        if len(lo_) < 8 or len(hi_) < 8:
            print(f"{rung:6s} {name:>26s}  -- degenerate split ({len(lo_)}/{len(hi_)}) --")
            continue
        a = _boot_med([r["e69"] for r in lo_], [r["blk"] for r in lo_])
        b = _boot_med([r["e69"] for r in hi_], [r["blk"] for r in hi_])
        print(f"{rung:6s} {name:>26s} {len(lo_):5d} {len(hi_):5d} | "
              f"{a[0]:8.1f} [{a[1]:6.1f},{a[2]:6.1f}] | {b[0]:8.1f} [{b[1]:6.1f},{b[2]:6.1f}] | "
              f"{b[0]/a[0]:8.3f}")
        OUT["t5"][rung] = dict(thr=thr, lo=list(a), hi=list(b), ratio=float(b[0] / a[0]))
    print("\n  ⚠ CONFOUNDED BY SPEED: every rung's duty falls with speed, and so does e_6-9.\n"
          "    The speed-matched version is the row below.")
    # speed-matched: within each 2 m/s bin, compare above/below the bin's own median duty
    for rung in ("b4", "b5"):
        rs_lo, rs_hi = [], []
        for lo, hi in ((0, 2), (2, 4), (4, 6), (6, 8), (8, 12), (12, 30)):
            m = [r for r in recs if lo <= r["v"] < hi]
            if len(m) < 10:
                continue
            thr = float(np.median([r[rung] for r in m]))
            rs_lo += [r for r in m if r[rung] <= thr]
            rs_hi += [r for r in m if r[rung] > thr]
        if len(rs_lo) < 8 or len(rs_hi) < 8:
            continue
        a = _boot_med([r["e69"] for r in rs_lo], [r["blk"] for r in rs_lo])
        b = _boot_med([r["e69"] for r in rs_hi], [r["blk"] for r in rs_hi])
        print(f"  speed-matched {rung}: LOW {a[0]:7.1f} [{a[1]:.1f},{a[2]:.1f}] (n={a[3]})  "
              f"HIGH {b[0]:7.1f} [{b[1]:.1f},{b[2]:.1f}] (n={b[3]})  ratio {b[0]/a[0]:.3f}")
        OUT["t5"][rung + "_speedmatched"] = dict(lo=list(a), hi=list(b), ratio=float(b[0] / a[0]))


