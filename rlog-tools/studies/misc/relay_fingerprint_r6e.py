# =====================================================================================================
#  T1 -- the odd-harmonic comb
# =====================================================================================================
def t1(W):
    hdr("T1  ODD-HARMONIC COMB.  prominence at k*f0 over the local floor, k = 2..5, with a DECOY\n"
        "    fundamental at f0 * 1.37 as the control.  A RELAY gives odd >> even; a resonance\n"
        "    gives no comb at all and the decoy reads the same as the real fundamental.")
    OUT["t1"] = {}
    print(f"{'build':10s} {'arm':8s} {'n':>5s} {'f0 med':>7s} | "
          f"{'h2':>6s} {'h3':>6s} {'h4':>6s} {'h5':>6s} | {'odd/even':>22s} | "
          f"{'DECOY odd/even':>22s}")
    for route, arm, recs in W:
        rs = [r for r in recs if np.isfinite(r["f0"])]
        if len(rs) < 10:
            print(f"{route:10s} {arm:8s} {len(rs):5d}  -- too few --")
            continue
        for r in rs:
            for k in (2, 3, 4, 5):
                r[f"h{k}"] = prom_at(r, k * r["f0"])
                r[f"d{k}"] = prom_at(r, k * r["f0"] * 1.37)
            odd = np.nanmean([r["h3"], r["h5"]])
            even = np.nanmean([r["h2"], r["h4"]])
            r["oe"] = odd / even if (np.isfinite(odd) and np.isfinite(even) and even > 0) else np.nan
            dodd = np.nanmean([r["d3"], r["d5"]])
            deven = np.nanmean([r["d2"], r["d4"]])
            r["oe_decoy"] = (dodd / deven if (np.isfinite(dodd) and np.isfinite(deven)
                                              and deven > 0) else np.nan)
        u = [r["blk"] for r in rs]
        hs = [float(np.nanmedian([r[f"h{k}"] for r in rs])) for k in (2, 3, 4, 5)]
        oe = _boot_med([r["oe"] for r in rs], u)
        de = _boot_med([r["oe_decoy"] for r in rs], u)
        print(f"{route:10s} {arm:8s} {len(rs):5d} {np.median([r['f0'] for r in rs]):7.2f} | "
              + " ".join(f"{h:6.2f}" for h in hs)
              + f" | {oe[0]:6.3f} [{oe[1]:6.3f},{oe[2]:6.3f}] | "
                f"{de[0]:6.3f} [{de[1]:6.3f},{de[2]:6.3f}]")
        OUT["t1"][f"{route}|{arm}"] = dict(n=len(rs), h=hs, oe=list(oe), decoy=list(de),
                                           f0=float(np.median([r["f0"] for r in rs])))
    print("\n  🛑 READ: odd/even ~ 1 AND decoy ~ the same ⇒ NO comb ⇒ no relay signature.")


# =====================================================================================================
#  T2 -- 3:1 phase locking
# =====================================================================================================
def t2(W):
    hdr("T2  3:1 PHASE LOCKING between f0 and 3*f0.  psi(t) = 3*phi_1(t) - phi_3(t); PLV = |<e^i psi>|\n"
        "    over the window.  NULL: the fundamental of window i against the 3rd harmonic of a\n"
        "    DIFFERENT window, which destroys the pairing and nothing else.")
    OUT["t2"] = {}
    print(f"{'build':10s} {'arm':8s} {'n':>5s} | {'PLV(3:1)':>22s} | {'shuffled NULL':>22s} | "
          f"{'z':>6s}")
    for route, arm, recs in W:
        rs = [r for r in recs if np.isfinite(r["f0"]) and 6.2 <= r["f0"] <= 8.8]
        if len(rs) < 10:
            print(f"{route:10s} {arm:8s} {len(rs):5d}  -- too few --")
            continue
        for r in rs:
            f0, fsr = r["f0"], r["fs"]
            b1 = butter(2, [max(f0 - 1.0, 0.5), f0 + 1.0], btype="band", fs=fsr)
            b3 = butter(2, [3 * f0 - 2.0, min(3 * f0 + 2.0, 0.48 * fsr)], btype="band", fs=fsr)
            s1 = hilbert(filtfilt(*b1, r["x"]))
            s3 = hilbert(filtfilt(*b3, r["x"]))
            r["_p1"], r["_p3"] = np.angle(s1), np.angle(s3)
            c = slice(NW // 8, -NW // 8)                      # drop filter edge transients
            r["plv"] = float(np.abs(np.mean(np.exp(1j * (3 * r["_p1"][c] - r["_p3"][c])))))
        # shuffled null: pair phi_1 of one window with phi_3 of another
        idx = RNG.permutation(len(rs))
        idx = np.where(idx == np.arange(len(rs)), (idx + 1) % len(rs), idx)
        c = slice(NW // 8, -NW // 8)
        for r, j in zip(rs, idx):
            r["plv_null"] = float(np.abs(np.mean(np.exp(
                1j * (3 * r["_p1"][c] - rs[j]["_p3"][c])))))
        u = [r["blk"] for r in rs]
        pv = _boot_med([r["plv"] for r in rs], u)
        nv = _boot_med([r["plv_null"] for r in rs], u)
        sd = float(np.std([r["plv_null"] for r in rs])) or np.nan
        z = (pv[0] - nv[0]) / sd if np.isfinite(sd) else np.nan
        print(f"{route:10s} {arm:8s} {len(rs):5d} | {pv[0]:6.4f} [{pv[1]:6.4f},{pv[2]:6.4f}] | "
              f"{nv[0]:6.4f} [{nv[1]:6.4f},{nv[2]:6.4f}] | {z:6.2f}")
        OUT["t2"][f"{route}|{arm}"] = dict(n=len(rs), plv=list(pv), null=list(nv), z=float(z))
        for r in rs:
            r.pop("_p1", None); r.pop("_p3", None)
    print("\n  🛑 READ: PLV indistinguishable from the shuffled null ⇒ the 3rd harmonic is NOT\n"
          "     phase-generated by the fundamental ⇒ no relay.")


# =====================================================================================================
#  T3 -- speed-locked vs fixed line
# =====================================================================================================
def t3(W):
    hdr("T3  SPEED-LOCKED vs FIXED LINE in 5-12 Hz -- the tyre/firmware split, and the best\n"
        "    available handle on micro- versus macro-ratcheting.")
    OUT["t3"] = {}
    for route, arm, recs in W:
        if arm != "engaged":
            continue
        rs = [r for r in recs if np.isfinite(r["f_free"])]
        if len(rs) < 20:
            continue
        for r in rs:
            r["p_fix"] = prom_at(r, MACRO, half=0.5)
            o2 = 2 * r["v"] / CIRC
            r["o2"] = o2
            r["p_o2"] = (prom_at(r, o2, half=0.5)
                         if (4.0 <= o2 <= 20.0 and abs(o2 - MACRO) >= 1.2) else np.nan)
        u = [r["blk"] for r in rs]
        pf = _boot_med([r["p_fix"] for r in rs], u)
        po = _boot_med([r["p_o2"] for r in rs], u)
        # does the FREE argmax track speed?
        v = np.array([r["v"] for r in rs]); ff = np.array([r["f_free"] for r in rs])
        A = np.vstack([v, np.ones_like(v)]).T
        slope = float(np.linalg.lstsq(A, ff, rcond=None)[0][0])
        near_fix = float(np.mean(np.abs(ff - MACRO) <= 0.6))
        near_o2 = float(np.mean([abs(r["f_free"] - r["o2"]) <= 0.6 for r in rs]))
        print(f"\n  {route}  n={len(rs)}")
        print(f"    prominence at the FIXED {MACRO} Hz line : {pf[0]:6.2f} [{pf[1]:5.2f},{pf[2]:5.2f}]"
              f"  (n={pf[3]})")
        print(f"    prominence at WHEEL ORDER 2            : {po[0]:6.2f} [{po[1]:5.2f},{po[2]:5.2f}]"
              f"  (n={po[3]}, order-2 away from {MACRO} Hz)")
        print(f"    free 5-12 Hz argmax: median {np.median(ff):5.2f} Hz, slope vs v "
              f"{slope:+.4f} Hz per m/s   (order-2 predicts +0.961, a fixed line 0.000)")
        print(f"    fraction of windows whose argmax is within 0.6 Hz of "
              f"{MACRO} Hz: {100*near_fix:5.1f}%   of order-2: {100*near_o2:5.1f}%")
        # speed-binned median of the free argmax -- the ridge test
        print(f"    {'v bin m/s':>12s} {'n':>4s} {'median argmax':>14s} {'order2':>8s}")
        for lo, hi in ((0, 2), (2, 4), (4, 6), (6, 8), (8, 11), (11, 16), (16, 40)):
            m = [r for r in rs if lo <= r["v"] < hi]
            if len(m) < 5:
                continue
            print(f"    {f'{lo}-{hi}':>12s} {len(m):4d} "
                  f"{np.median([r['f_free'] for r in m]):14.2f} "
                  f"{np.median([r['o2'] for r in m]):8.2f}")
        OUT["t3"][route] = dict(n=len(rs), p_fix=list(pf), p_o2=list(po), slope=slope,
                                near_fix=near_fix, near_o2=near_o2,
                                f_free_med=float(np.median(ff)))
    print("\n  🛑 READ: a slope near +0.961 and argmax tracking order 2 ⇒ the 6-9 Hz band on that\n"
          "     route is largely TYRE, not firmware.  A slope near 0 with a fixed ridge ⇒ firmware.")


# =====================================================================================================
#  T4 -- switching-surface timing
# =====================================================================================================
def t4(W):
    hdr("T4  SWITCHING-SURFACE TIMING.  Zero-crossing-triggered average of the 6-9 Hz envelope,\n"
        "    triggered on the 0.5-4 Hz residual's zero crossings.  Bands are DISJOINT.\n"
        "    NULL: the same count of pseudo-crossings placed uniformly at random.")
    OUT["t4"] = {}
    LAGS = np.arange(-30, 31)                    # +-0.3 s at ~101 Hz
    print(f"{'build':10s} {'arm':8s} {'n win':>6s} {'n cross':>8s} | "
          f"{'peak lag ms':>12s} {'ETA peak / baseline':>21s} | {'NULL peak/base':>16s}")
    for route, arm, recs in W:
        rs = [r for r in recs if len(r["env"]) == NW]
        if len(rs) < 10:
            continue
        acc, accn, ncr = [], [], 0
        for r in rs:
            e = r["env"] / (np.median(r["env"]) + 1e-9)
            z = r["x_lf"]
            cr = np.flatnonzero((z[:-1] < 0) & (z[1:] >= 0)) + 1
            cr = cr[(cr > 40) & (cr < NW - 40)]
            if len(cr) < 2:
                continue
            ncr += len(cr)
            acc.append(np.mean([e[c + LAGS] for c in cr], axis=0))
            pc = RNG.integers(40, NW - 40, len(cr))
            accn.append(np.mean([e[c + LAGS] for c in pc], axis=0))
        if not acc:
            continue
        A = np.mean(acc, axis=0); N = np.mean(accn, axis=0)
        base = np.mean(np.r_[A[:10], A[-10:]])
        pk = int(np.argmax(A))
        nbase = np.mean(np.r_[N[:10], N[-10:]])
        print(f"{route:10s} {arm:8s} {len(acc):6d} {ncr:8d} | "
              f"{1000*LAGS[pk]/101.0:12.1f} {A[pk]/base:21.4f} | "
              f"{np.max(N)/nbase:16.4f}")
        OUT["t4"][f"{route}|{arm}"] = dict(n=len(acc), ncross=ncr,
                                           peak_lag_ms=float(1000 * LAGS[pk] / 101.0),
                                           eta=float(A[pk] / base),
                                           null=float(np.max(N) / nbase),
                                           curve=[float(x) for x in A])
    print("\n  🛑 READ: ETA peak/baseline at the SAME level as the random-placement null ⇒ the\n"
        "     6-9 Hz envelope is NOT time-locked to the residual's switching surface.")


