def w0():
    hdr("W0  WHEEL-ORDER-CLEAN RE-TEST.  🛑 Route 6e's speed distribution puts wheel ORDER 2\n"
        "    (2v/2.0805 Hz) inside 6-9 Hz on 20.7% of engaged windows, against route 6d's 6.7%\n"
        "    and route 67's 8.7%.  Any 6-9 Hz ratio must survive dropping those windows.")
