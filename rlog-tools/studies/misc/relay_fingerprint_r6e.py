def _boot_med(vals, units, nboot=2000):
    """Median with an EPISODE bootstrap CI. `units` is the resampling-unit label per value."""
    vals = np.asarray(vals, float)
    ok = np.isfinite(vals)
    vals, units = vals[ok], np.asarray(units)[ok]
    if len(vals) < 4:
        return np.nan, np.nan, np.nan, len(vals)
    groups = {}
    for v, u in zip(vals, units):
        groups.setdefault(u, []).append(v)
    keys = list(groups)
    draws = np.empty(nboot)
    for k in range(nboot):
        idx = RNG.integers(0, len(keys), len(keys))
        draws[k] = np.median(np.concatenate([groups[keys[i]] for i in idx]))
    return (float(np.median(vals)), float(np.percentile(draws, 2.5)),
            float(np.percentile(draws, 97.5)), len(vals))


