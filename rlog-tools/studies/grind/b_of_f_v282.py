# The 0xC6446 arm implied by inverting the cave bit-6 duty onto the closed-form ladder,
# median over 18 stratum x route cells (range 2268-2747, median 2353).  The flown cell is 5244.
GAIN_EFFECTIVE = 2353.0
GAIN_FLOWN = 5244.0

def _rows(stratum, route="V282pool"):
    k = "%s|%s" % (stratum, route)
    if k not in TABLE:
        raise KeyError("no table for %s ; have %s" % (k, sorted(TABLE)))
    return np.asarray(TABLE[k], float)


def is_usable(f, stratum="loaded_any", route="V282pool"):
    """True where the measurement identifies B at f (coherence >= 0.40 at the nearest tabulated point)."""
    r = _rows(stratum, route)
    return np.interp(np.asarray(f, float), r[:, 0], r[:, 5]) >= COH_MIN


def coherence(f, stratum="loaded_any", route="V282pool"):
    r = _rows(stratum, route)
    return np.interp(np.asarray(f, float), r[:, 0], r[:, 5])


def B_table(f, stratum="loaded_any", route="V282pool", which="Hv"):
    """Measured B(f) by interpolation: log-linear in magnitude, linear in UNWRAPPED phase, over the
    coherence-usable points only.  Returns a complex array.  Outside 3-30 Hz this EXTRAPOLATES -- use
    B_fit() there instead."""
    r = _rows(stratum, route)
    col = {"H1": 1, "Hv": 2, "H2": 3}[which]
    ok = r[:, 5] >= COH_MIN
    fu, mu, pu = r[ok, 0], r[ok, col], np.unwrap(np.radians(r[ok, 4]))
    f = np.asarray(f, float)
    return np.exp(np.interp(f, fu, np.log(mu))) * np.exp(1j * np.interp(f, fu, pu))


def _H(p, f, kind):
    f = np.asarray(f, float)
    if kind == "Z1":
        return (1j * f) / (1 - (f / p["fn"]) ** 2 + 2j * p["zeta"] * (f / p["fn"]))
    if kind == "Z1P":
        return (1j * f) / ((1 - (f / p["fn"]) ** 2 + 2j * p["zeta"] * (f / p["fn"])) * (1 + 1j * f / p["fp"]))
    if kind == "Z1PZ":
        return ((1j * f) * (1 + 1j * f / p["fz"])
                / ((1 - (f / p["fn"]) ** 2 + 2j * p["zeta"] * (f / p["fn"])) * (1 + 1j * f / p["fp"])))
    if kind == "Z1PP":
        return (1j * f) / ((1 - (f / p["fn"]) ** 2 + 2j * p["zeta"] * (f / p["fn"]))
                           * (1 - (f / p["f2"]) ** 2 + 2j * p["zeta2"] * (f / p["f2"])))
    if kind == "INT":
        return 1.0 / ((1j * f) * (1 - (f / p["fn"]) ** 2 + 2j * p["zeta"] * (f / p["fn"])))
    raise ValueError(kind)


def B_fit(f, stratum="loaded_any", kind="Z1P", band="6-25"):
    """Parametric B(f).  kind in {Z1, Z1P, Z1PZ, Z1PP, INT}; band in {'6-25','3-30'}.
    Z1/Z1P are the recommended families: B has a ZERO AT THE ORIGIN (bar twist -> 0 at DC), not the
    integrator the 'spring' reading would give.  INT is kept only to show it fits ~3x worse."""
    k = "%s|V282pool|%s" % (stratum, band.replace("-", "-"))
    if k not in FITS:
        raise KeyError("no fit for %s ; have %s" % (k, sorted(FITS)))
    p = FITS[k][kind]
    f = np.asarray(f, float)
    return p["A"] * np.exp(1j * p["phi0"]) * _H(p, f, kind) * np.exp(-2j * np.pi * f * p["tau"])


def D4(f, N=4, fs1k=1000.0):
    """the lane's 4-tap backward difference at 1 kHz, exactly as the firmware computes it."""
    return 0.5 * (1.0 - np.exp(-2j * np.pi * np.asarray(f, float) * N / fs1k))


def R_r24(f, gain=GAIN_EFFECTIVE, stratum="loaded_any", route="V282pool", source="table", **kw):
    """The r24 lane cell gp-0x6ada per unit of x = -rate (internal rate).  POSITIVE REAL PART = DAMPING.

    gain defaults to GAIN_EFFECTIVE (2353), the arm implied by the cave's bit-6 duty on the wire, NOT the
    flown 0xC6446 = 5244 -- the wire magnitude is 0.43-0.52 of the closed form on every stratum and both
    routes.  Pass gain=5244.0 for the closed-form (phase-correct, magnitude ~2.3x too big) value.
    source: 'table' (measured, 3-30 Hz only) or 'fit' (parametric, any f)."""
    B = B_table(f, stratum, route, **kw) if source == "table" else B_fit(f, stratum, **kw)
    return -(gain / 1024.0) * D4(f) * B
